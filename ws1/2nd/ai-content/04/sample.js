function setup() {
    createCanvas(600, 400);
    rectMode(CENTER);
    imageMode(CENTER);
    angleMode(DEGREES);
    colorMode(HSB, 360, 100, 100, 100);
}

function draw() {
    // --------------------------------------------------
    // 1. 残像エフェクトと発光準備
    // --------------------------------------------------
    // 通常合成に戻してから半透明の背景を塗り重ねることで、前のフレームの絵が少しずつ消え、滑らかな残像になります
    blendMode(BLEND);
    background(230, 80, 10, 15);

    // 加算合成（光が重なるほど明るくなるモード）に切り替え、発光感を演出します
    blendMode(ADD);

    // --------------------------------------------------
    // 2. クラゲ全体の移動と「呼吸（脈動）」の計算
    // --------------------------------------------------
    push(); // クラゲ全体の座標系を保存

    // 画面の中央を基準に、sin() を使って上下にゆったりと漂わせます
    // frameCount はプログラム開始からのコマ数。角度として渡すことで周期的に変化します
    let floatY = sin(frameCount * 1.5) * 20;
    translate(width / 2, height / 2 - 30 + floatY);

    // クラゲ全体もわずかに左右へ傾けて水流を表現します（-5度〜+5度）
    rotate(sin(frameCount * 0.8) * 5);

    // --------------------------------------------------
    // 4. クラゲの傘（本体）の描画：sin() による脈動と回転配置
    // --------------------------------------------------
    push(); // 傘の座標系を保存

    // sin() を使って、縦横に伸縮する「呼吸（脈動）」の動きを作ります
    // 横幅が広がるときに縦が縮むようにすると、水を押し出す生き物らしい動きになります
    let pulseX = map(sin(frameCount * 3), -1, 1, 0.85, 1.15);
    let pulseY = map(sin(frameCount * 3), -1, 1, 1.1, 0.85);
    scale(pulseX, pulseY);

    // 傘の内部にある発光器官を、rotate() を使って扇状に配置します
    noFill();
    for (let angle = -75; angle <= 75; angle += 15) {
        push();
        rotate(angle); // 中心を軸に角度を少しずつ変える

        // 角度によってシアン〜青〜青紫へと色が変化するグラデーション
        let coreHue = map(angle, -75, 75, 185, 255);
        stroke(coreHue, 85, 100, 25);
        strokeWeight(2);

        // rectMode(CENTER) を活かし、角丸の長方形で光の筋を描きます
        rect(0, -25, 16, 55, 10);
        pop();
    }

    // 傘の外側のシルエットを、少しずつ大きさを変えた半円（arc）を重ねてふんわり光らせます
    noStroke();
    for (let k = 0; k < 5; k++) {
        let glowHue = map(k, 0, 4, 190, 240);
        fill(glowHue, 80, 90, 12);
        // 180度から360度までを指定して、上向きの半円を描きます（度数法）
        arc(0, 15, 160 - k * 20, 130 - k * 15, 180, 360);
    }

    pop(); // 傘の座標系を戻す
    pop(); // クラゲ全体の座標系を戻す

    // --------------------------------------------------
    // 5. 背景の演出：深海を漂う光の粒（マリンスノー）
    // --------------------------------------------------
    noStroke();
    for (let m = 0; m < 12; m++) {
        // 粒ごとに異なる noise() の座標を与え、画面内をふわふわと漂わせます
        let px = noise(m * 100, frameCount * 0.002) * width;
        let py = noise(m * 200, frameCount * 0.002) * height;
        let pSize = map(sin(frameCount * 2 + m * 30), -1, 1, 2, 7);

        fill(200, 60, 100, 30);
        circle(px, py, pSize);
    }
}